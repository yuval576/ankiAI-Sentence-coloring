import {DeckMemory} from './deck-memory.mjs';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'anki-memory-test-'));
let memory=new DeckMemory(dir);
memory.update({instructions:'Use simple Spanish.',memoryEnabled:true});
memory.record({word:'к'},'Which case follows к?','Dative.',memory.generation);
memory=new DeckMemory(dir);
assert.equal(memory.info().instructions,'Use simple Spanish.');
assert.equal(memory.select({word:'идти'},'Which case follows к?')[0].answer,'Dative.');
assert.throws(()=>memory.update({instructions:'x'.repeat(4001),memoryEnabled:true}));
assert.throws(()=>memory.update({instructions:'',memoryEnabled:true,memoryNotes:'Manual memory is not editable'}));
memory.update({instructions:'',memoryEnabled:false});
memory.record({word:'test'},'Do not remember this.','Okay.',memory.generation);
assert.equal(memory.entries.length,1);assert.deepEqual(memory.select({word:'к'},'case'),[]);
const oldGeneration=memory.generation;
memory.clear();memory.update({instructions:'',memoryEnabled:true});
memory.record({word:'old'},'In-flight old request','Old answer',oldGeneration);
assert.equal(memory.entries.length,0);
console.log('PASS: persistent shared preferences, cross-card retrieval, validation, memory off, clear and in-flight clear protection.');
